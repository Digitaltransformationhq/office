-- DSC REGISTER: every Digital Signature Certificate the office holds or tracks.
--
-- Run this in the Supabase SQL editor before deploying the edge function that
-- reads it. It is safe to re-run.
--
-- One row per certificate (not per person): a renewal is a new certificate with
-- a new expiry, so the old row stays as history and the new one is added.
--
-- `password` is the token PIN. It is never returned by the list endpoint; the
-- edge function hands it out one row at a time, to admins only.

BEGIN;

CREATE TABLE IF NOT EXISTS public.dsc_register (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  holder_name TEXT NOT NULL,
  company_name TEXT NOT NULL DEFAULT '',
  client_id TEXT REFERENCES public.clients(id) ON DELETE SET NULL,
  dsc_class TEXT NOT NULL DEFAULT '',
  expiry_date DATE,
  password TEXT NOT NULL DEFAULT '',
  notes TEXT NOT NULL DEFAULT '',
  needs_review BOOLEAN NOT NULL DEFAULT FALSE,
  review_note TEXT NOT NULL DEFAULT '',
  source TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_by_name TEXT NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS idx_dsc_register_expiry ON public.dsc_register (expiry_date);
CREATE INDEX IF NOT EXISTS idx_dsc_register_client ON public.dsc_register (client_id);

COMMENT ON TABLE public.dsc_register IS
  'Digital Signature Certificates held for clients: holder, expiry and token PIN.';
COMMENT ON COLUMN public.dsc_register.source IS
  'Where the row came from, e.g. "DSC sheet p1 #4"; blank for rows added in the app.';

-- Server-only table: the edge function uses the service role, which bypasses
-- RLS. No policies, so the public anon key can read nothing (passwords live here).
ALTER TABLE public.dsc_register ENABLE ROW LEVEL SECURITY;

-- In / Out history of each DSC token: received into the office or handed back.
-- The latest row tells whether the token is in the office right now.
CREATE TABLE IF NOT EXISTS public.dsc_movements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dsc_id BIGINT NOT NULL REFERENCES public.dsc_register(id) ON DELETE CASCADE,
  direction TEXT NOT NULL CHECK (direction IN ('IN', 'OUT')),
  transfer_method TEXT NOT NULL,
  details TEXT NOT NULL DEFAULT '',
  recorded_by_id TEXT REFERENCES public.users(id) ON DELETE SET NULL,
  recorded_by_name TEXT NOT NULL,
  recorded_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_dsc_movements_dsc
  ON public.dsc_movements (dsc_id, recorded_at DESC);

ALTER TABLE public.dsc_movements ENABLE ROW LEVEL SECURITY;

COMMIT;
