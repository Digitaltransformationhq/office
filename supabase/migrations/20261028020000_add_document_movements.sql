BEGIN;

CREATE TABLE IF NOT EXISTS public.document_movements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id TEXT REFERENCES public.clients(id) ON DELETE SET NULL,
  client_name TEXT NOT NULL,
  direction TEXT NOT NULL CHECK (direction IN ('IN', 'OUT')),
  document_type TEXT NOT NULL,
  transfer_method TEXT NOT NULL,
  details TEXT NOT NULL DEFAULT '',
  recorded_by_id TEXT REFERENCES public.users(id) ON DELETE SET NULL,
  recorded_by_name TEXT NOT NULL,
  recorded_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_document_movements_client
  ON public.document_movements (client_id, recorded_at DESC);

CREATE INDEX IF NOT EXISTS idx_document_movements_recorded_at
  ON public.document_movements (recorded_at DESC);

COMMENT ON TABLE public.document_movements IS
  'Audit history of physical or digital client documents received by and released from the office.';

COMMIT;
